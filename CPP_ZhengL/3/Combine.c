    {
        scanf("%d,",&input);
        if(input!=0)
        {
            a[i]=input;
            i++;
        }
        else
        {
            if(j!=size)
            {
                j++;
                continue;
            }
            else
            break;
        }
    }
    for(k=0;k<i-1;k++)
    {
    for(j=0;j<i-1-k;j++)
    {
        if(a[j]>a[j+1])
        {
            t=a[j];
            a[j]=a[j+1];
            a[j+1]=t;
        }
    }
    }
